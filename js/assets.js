// Quick helper to get image by category or random fallback
window.getNatureAsset = function(category, index = 0) {
  const norm = (category || '').toString().toLowerCase().trim();
  const mapped = CATEGORY_MAP[norm] || category || '';
  const filtered = window.NATURE_ASSETS.filter(a => a.category.toLowerCase() === mapped.toLowerCase());
  if (filtered.length > 0) {
    return filtered[Math.abs(index) % filtered.length].path;
  }
  return window.NATURE_ASSETS[Math.abs(index) % window.NATURE_ASSETS.length].path;
};

// Global fallback handler for broken <img> tags anywhere in the app
window.handleImageError = function(imgEl, category = 'Nature', seed = 0) {
  if (!imgEl || imgEl.dataset.hasFailedFallback) return;
  imgEl.dataset.hasFailedFallback = 'true';
  const fallback = window.getNatureAsset(category, seed);
  imgEl.src = fallback;
};

